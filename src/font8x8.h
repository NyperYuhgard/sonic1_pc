/* Blit an ASCII string using font8x8 at (x, y) into an ARGB8888 buffer.
   `pitch` is the row stride in BYTES; `max_w`/`max_h` are the buffer
   dimensions used to clip every pixel (safe for scrolled/centered views).
   Glyph advance = 6 px, height = 8 px. */
static inline void font8x8_blit(uint32_t *px, int pitch, int max_w, int max_h,
                                int x, int y, const char *s, uint32_t color) {
    for (const char *c = s; *c; c++) {
        unsigned ch = (unsigned char)*c;
        if (ch < ' ' || ch > '_') ch = ' ';
        const uint8_t *g = font8x8[ch - ' '];
        for (int r = 0; r < 8; r++) {
            uint8_t bits = g[r];
            for (int cc = 0; cc < 8; cc++) {
                if (bits & (0x80 >> cc)) {
                    int xx = x + cc, yy = y + r;
                    if (xx >= 0 && yy >= 0 && xx < max_w && yy < max_h) {
                        px[yy * (pitch / 4) + xx] = color;
                    }
                }
            }
        }
        x += 6;
    }
}

/* As above, but with a dark 1px drop shadow for readability on busy
   backgrounds. */
static inline void font8x8_blit_shadow(uint32_t *px, int pitch, int max_w,
                                       int max_h, int x, int y,
                                       const char *s, uint32_t color) {
    font8x8_blit(px, pitch, max_w, max_h, x + 1, y + 1, s, 0xFF000000);
    font8x8_blit(px, pitch, max_w, max_h, x, y, s, color);
}

